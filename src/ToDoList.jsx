import { useState } from 'react';
import {v4 as uuidv4} from 'uuid';

export default function ToDoList() {
    let [todos, setTodos] = useState([{task: "Sample-task", id: uuidv4()}]);
    let [newTask, setNewTask] = useState("");// To store the value of the input field, In the first render, it will be empty, ""

    const addTask = () => {
        setTodos((prevTodos) => {
            return [...prevTodos, {task: newTask, id: uuidv4()}]
        });
        setNewTask("");//To refresh the input field after adding a task
    }

    const updatevalue = (event) => {
        setNewTask(event.target.value);
    }

    const deleteToDo = (id) => {
        console.log("Deleting task with id: ", id);
        setTodos((prevTodos) => {
            return prevTodos.filter(
                (todo) => todo.id !== id
            );
        });
    }

    const updateAllToUppercase = () => {
        setTodos((prevTodos) => {
            return prevTodos.map((todo) => {
                return { ...todo, task: todo.task.toUpperCase() };
            });
        });
    }

//set function is used to update the state of the component. It takes a function as an argument, which receives the previous state (prevTodos) and returns the new state. In this case, it creates a new array that includes all the previous todos and adds a new todo object with the task and a unique id generated by uuidv4().
//also it renders the component again with the updated state, which will reflect the changes in the UI.
//When I click a delete button, it will call the deleteToDo function with the id of the task to be deleted. The function will filter out the task with that id from the todos array and update the state accordingly, which will also trigger a re-render of the component to reflect the changes in the UI.

    return(
        <div>
            <input placeholder="Add a new task..." value={newTask} onChange = { updatevalue } ></input>
            <br></br><br></br>
            <button onClick={addTask}> Add Task</button>
            <br></br>
            <hr></hr>
            <h4>Task to do</h4>
            <ul>
                {
                todos.map((todo) => 
                <li key = {todo.id}> 
                    <span> {todo.task} </span>
                    <button onClick = {() => deleteToDo(todo.id)}> Delete task </button>
                </li>
                )}
            </ul>
            <button onClick = { updateAllToUppercase }>Uppercase all</button>
        </div>
    )
}